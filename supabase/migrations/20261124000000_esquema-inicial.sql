-- Esquema de Genie en Supabase (migración desde InsForge, noviembre 2026).
-- Equivale a migrations/ (InsForge) aplicado hasta 20261123210000, en una sola
-- migración. El servidor usa la clave service_role: las tablas tienen RLS
-- activado, sin políticas, y anon/authenticated no tienen permisos (nadie las
-- lee desde el navegador).

create table if not exists organizaciones (
  slug text primary key check (slug ~ '^[a-z0-9-]{2,40}$'),
  nombre text not null,
  plan text not null default 'manual',
  estado text not null default 'activa' check (estado in ('activa', 'suspendida')),
  creado_en timestamptz not null default now()
);

-- Administradores por institución. Hoy no se usa (toda cuenta con sesión
-- administra el panel), pero queda lista para cuando haya otra institución.
create table if not exists miembros (
  user_id uuid not null references auth.users(id) on delete cascade,
  organizacion text not null references organizaciones(slug) on delete cascade,
  rol text not null default 'admin' check (rol in ('admin')),
  creado_en timestamptz not null default now(),
  primary key (user_id, organizacion)
);

create table if not exists certificados (
  id uuid primary key default gen_random_uuid(),
  organizacion text not null references organizaciones(slug),
  -- Persona: nombre normalizado (clave) y tal como se escribió.
  clave text not null,
  clave_original text not null,
  nombre text not null,
  tipo text not null check (tipo in (
    'asistente', 'ponente', 'conferencista', 'coordinador_mesa',
    'panelista', 'moderador_panel', 'moderadora_panel'
  )),
  -- Qué certificado de la persona es: "<tipo>:<título normalizado>".
  referencia text not null default '',
  datos jsonb not null default '{}'::jsonb,
  correos text[] not null default '{}',
  -- Plantilla del evento con que se generó (null: "otro evento") y su versión.
  plantilla text,
  plantilla_version text,
  archivo_key text not null,
  busqueda text not null default '',
  descargas int not null default 0,
  ultima_descarga timestamptz,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint certificados_organizacion_clave_referencia_key unique (organizacion, clave, referencia)
);

create index if not exists certificados_nombre_idx on certificados (nombre);
create index if not exists certificados_tipo_idx on certificados (tipo);
create index if not exists certificados_organizacion_nombre_idx on certificados (organizacion, nombre);
create index if not exists certificados_organizacion_clave_idx on certificados (organizacion, clave);
create index if not exists certificados_correos_idx on certificados using gin (correos);

create table if not exists solicitudes (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  correo text not null,
  institucion text,
  mensaje text,
  creado_en timestamptz not null default now()
);

-- "by default" (no "always"): permite importar la bitácora con sus ids.
create table if not exists bitacora (
  id bigint generated by default as identity primary key,
  creado_en timestamptz not null default now(),
  organizacion text,
  evento text not null,
  resultado text not null
    check (resultado in ('ok', 'no_encontrado', 'rechazado', 'limite', 'error')),
  estado_http int,
  mensaje text,
  actor text,
  certificado_id uuid,
  origen text,
  ip text,
  user_agent text,
  duracion_ms int,
  detalle jsonb not null default '{}'::jsonb
);

create index if not exists bitacora_organizacion_creado_idx on bitacora (organizacion, creado_en desc);
create index if not exists bitacora_evento_idx on bitacora (evento);
create index if not exists bitacora_certificado_idx on bitacora (certificado_id);

alter table organizaciones enable row level security;
alter table miembros enable row level security;
alter table certificados enable row level security;
alter table solicitudes enable row level security;
alter table bitacora enable row level security;

revoke all on table organizaciones, miembros, certificados, solicitudes, bitacora from anon, authenticated;
revoke all on sequence bitacora_id_seq from anon, authenticated;

-- Bucket privado de PDFs y plantillas personalizadas (solo service_role).
insert into storage.buckets (id, name, public)
values ('certificados', 'certificados', false)
on conflict (id) do nothing;
